SET DEFINE OFF;

BEGIN
   FOR cur_rec IN (SELECT table_name FROM user_tables WHERE table_name IN ('COMPONENT_IMAGES', 'ISSUE_RECORDS', 'LAB_COMPONENTS', 'BRANCH_LABS', 'ACADEMIC_BRANCHES', 'SYSTEM_USERS')) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || cur_rec.table_name || ' CASCADE CONSTRAINTS';
   END LOOP;
END;
/

CREATE TABLE system_users (
    user_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) DEFAULT 'ADMIN' NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

